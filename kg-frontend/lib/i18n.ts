export function formatReviewInterval(days: number, locale: Locale): string {
  let value = Math.max(1, days);
  let unit: "day" | "month" | "year" = "day";
  if (days >= 30) {
    const months = Math.round(days / 30);
    if (months < 12) { value = months; unit = "month"; }
    else { value = Number((days / 365).toFixed(1)); unit = "year"; }
  }
  const viUnits = { day: "ngày", month: "tháng", year: "năm" };
  if (locale === "vi") return `${value} ${viUnits[unit]}`;
  return `${value} ${unit}${value === 1 ? "" : "s"}`;
}

export function readLocale(storage: Pick<Storage, "getItem">): Locale {
  try { return storage.getItem(LOCALE_KEY) === "en" ? "en" : "vi"; } catch { return "vi"; }
}

export function translateText(input: string | null | undefined, locale: Locale, values: Record<string, string | number> = {}): string {
  const source = input ?? "";
  const key = source.trim();
  const translated = locale === "en" ? messages[key] ?? messages[source] ?? key : viLabels[key] ?? key;
  const padded = source.slice(0, source.indexOf(key)) + translated + source.slice(source.indexOf(key) + key.length);
  return padded.replace(/\{(\w+)\}/g, (match, name: string) => values[name] === undefined ? match : String(values[name]));
}
